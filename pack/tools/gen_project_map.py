"""Keeps PROJECT_MAP.md true: writes its file index from the code itself and checks that the map covers the repository.

  python pack/tools/gen_project_map.py           rewrite the index part of PROJECT_MAP.md (between the index markers)
  python pack/tools/gen_project_map.py --check   change nothing; exit 1 when the index is out of date, or when a folder
                                                 of the repository is not described in the hand-written part

The index lists every code file the repository tracks (Java, Python, C#, JavaScript, shell) with the first sentence of
its own documentation: the module docstring of a Python file, the Javadoc of a Java class, the summary of a C# file, the
first comment of a script. So a file is described where it lives, and the map follows by running this script. A file
without documentation shows "(no description)": write one in the file, not here.

Run it after every change to the repository (AGENTS.md); `python pack/tools/install_hooks.py` makes git refuse a commit
whose map is out of date, and rebuilds the graphify graph (graphify-out/) after each commit.
"""
import ast
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
MAP = os.path.join(ROOT, "PROJECT_MAP.md")
BEGIN, END = "<!-- index:begin (generated by pack/tools/gen_project_map.py, do not edit by hand) -->", "<!-- index:end -->"
CODE = (".java", ".py", ".cs", ".js", ".sh", ".xaml")
# folders whose every subfolder the hand-written part must name (others: their own name is enough)
DEEP = ("pack/overrides/", "pack/overrides/kubejs/", "pack/overrides/config/", "pack/tools/", "pack/i18n/", "mods-src/", "launcher/",
        "mods-src/wilds_core/src/main/java/ua/wilds/core/", "mods-src/wilds_wiki/src/main/java/ua/wilds/wiki/")


def tracked():
    out = subprocess.run(["git", "-c", "core.quotepath=off", "ls-files", "--cached", "--others", "--exclude-standard"], cwd=ROOT, capture_output=True, text=True, encoding="utf-8", check=True).stdout
    return sorted(l for l in out.splitlines() if l)


def first_sentence(text, limit=180):
    text = re.sub(r"\{@(?:link|code) ([^}]*)\}", r"\1", text)
    text = re.sub(r"<[^>]+>", "", text)
    text = " ".join(text.split())
    m = re.match(r"(.+?[.!?])(\s|$)", text)
    s = m.group(1) if m else text
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0] + "…"
    return s.replace("|", "\\|")


def describe(path):
    full = os.path.join(ROOT, path)
    try:
        src = open(full, encoding="utf-8", errors="replace").read()
    except OSError:
        return ""
    ext = os.path.splitext(path)[1]
    if ext == ".py":
        try:
            doc = ast.get_docstring(ast.parse(src))
        except SyntaxError:
            doc = None
        return first_sentence(doc.split("\n\n")[0]) if doc else ""
    if ext == ".java":
        # the Javadoc right before the top-level type
        m = re.search(r"/\*\*(.*?)\*/\s*(?:@[\w.]+(?:\([^)]*\))?\s*)*(?:public|final|abstract|class|interface|enum|record)", src, re.S)
        if not m:
            return ""
        body = re.sub(r"^\s*\*\s?", "", m.group(1), flags=re.M)
        body = body.split("<p>")[0].split("\n\n")[0]
        return first_sentence(body)
    if ext == ".cs":
        m = re.search(r"<summary>(.*?)</summary>", src, re.S)
        if m:
            return first_sentence(re.sub(r"^\s*///\s?", "", m.group(1), flags=re.M))
        m = re.search(r"^((?:\s*//[^\n]*\n)+)", src)
        return first_sentence(re.sub(r"^\s*//\s?", "", m.group(1), flags=re.M)) if m else ""
    if ext == ".xaml":
        m = re.match(r"\s*<!--(.*?)-->", src.lstrip(chr(0xFEFF)), re.S)
        return first_sentence(m.group(1)) if m else ""
    if ext in (".js", ".sh"):
        lines = []
        for l in src.splitlines():
            s = l.strip()
            if s.startswith("#!") or (not lines and not s):
                continue
            if s.startswith("//") or (ext == ".sh" and s.startswith("#")):
                lines.append(s.lstrip("/#").strip())
            else:
                break
        return first_sentence(" ".join(lines)) if lines else ""
    return ""


def index(files):
    code = [f for f in files if f.endswith(CODE)]
    groups = {}
    for f in code:
        groups.setdefault(os.path.dirname(f), []).append(f)
    out = [BEGIN, "", f"Every code file of the repository ({len(code)}), with the first sentence of its own documentation.", ""]
    for d in sorted(groups):
        out.append(f"### `{d}/`")
        out.append("")
        out.append("| File | What it is |")
        out.append("|---|---|")
        for f in groups[d]:
            out.append(f"| `{os.path.basename(f)}` | {describe(f) or '(no description)'} |")
        out.append("")
    # data folders: how much lives where (what they are is in the hand-written part)
    counts = {}
    for f in files:
        if f.endswith(CODE):
            continue
        parts = f.split("/")
        key = "/".join(parts[:3]) + "/" if len(parts) > 3 else "/".join(parts[:-1]) + "/" if len(parts) > 1 else "(root)"
        counts[key] = counts.get(key, 0) + 1
    out.append("### Data files by folder")
    out.append("")
    out.append("| Folder | Files |")
    out.append("|---|---|")
    for k in sorted(counts):
        out.append(f"| `{k}` | {counts[k]} |")
    out.append("")
    out.append(END)
    return "\n".join(out)


def folders(files):
    """the folders the hand-written part must name"""
    need = set()
    for f in files:
        parts = f.split("/")
        for depth in range(1, len(parts)):
            d = "/".join(parts[:depth]) + "/"
            parent = "/".join(parts[:depth - 1]) + "/" if depth > 1 else ""
            if depth <= 2 or parent in DEEP:
                need.add(d)
    return sorted(need)


def main():
    check = "--check" in sys.argv
    files = tracked()
    text = open(MAP, encoding="utf-8").read()
    if BEGIN not in text or END not in text:
        sys.exit("PROJECT_MAP.md has no index markers")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + index(files) + tail
    problems = []
    for d in folders(files):
        if f"`{d}`" not in head and f"`{d.rstrip('/')}`" not in head:
            problems.append(f"folder {d} is not described in PROJECT_MAP.md")
    if check:
        if new != text:
            problems.append("the file index of PROJECT_MAP.md is out of date: run python pack/tools/gen_project_map.py")
        for p in problems:
            print(p)
        sys.exit(1 if problems else 0)
    if new != text:
        open(MAP, "w", encoding="utf-8", newline="\n").write(new)
        print("PROJECT_MAP.md index updated")
    for p in problems:
        print("warning:", p)


if __name__ == "__main__":
    main()
