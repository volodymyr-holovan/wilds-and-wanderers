"""Write kubejs/server_scripts/wilds_ore_magnet.js: the Twilight Forest Ore Magnet pulls the ores of every mod.

The magnet pairs two block tags by name: an ore in c:ores_in_ground/<x> is pulled out and replaced by the block in
c:ore_bearing_ground/<x>. Mekanism, Create, Ice and Fire and Iron's Spells already tag their stone and deepslate
ores; the ores Seamless Ores puts into andesite, tuff, calcite, Create's stones and so on, and the ores of the Aether
and Alex's Caves, have no such tag. This gives each of them a group named after its host stone, so the magnet leaves
the right stone behind, and lets the magnet work through those stones. Coal stays ignored, as the magnet intends.
  python gen_ore_magnet.py   (reads docs/registries/item.txt; rerun after adding a mod with ores)
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ITEMS = os.path.join(HERE, "..", "..", "docs", "registries", "item.txt")
OUT = os.path.join(HERE, "..", "overrides", "kubejs", "server_scripts", "wilds_ore_magnet.js")

# Seamless Ores id prefix -> host stone (the longest prefix wins)
SEAMLESS = {
    "andesite": "minecraft:andesite", "diorite": "minecraft:diorite", "granite": "minecraft:granite",
    "tuff": "minecraft:tuff", "dripstone": "minecraft:dripstone_block", "basalt": "minecraft:basalt",
    "blackstone": "minecraft:blackstone", "minecraft_blackstone": "minecraft:blackstone",
    "minecraft_calcite": "minecraft:calcite", "minecraft_smooth_basalt": "minecraft:smooth_basalt",
    "create_asurine": "create:asurine", "create_crimsite": "create:crimsite", "create_limestone": "create:limestone",
    "create_ochrum": "create:ochrum", "create_scorchia": "create:scorchia", "create_scoria": "create:scoria",
    "create_veridium": "create:veridium",
}
# ores of other mods in their own stone
OTHER = {
    "aether:holystone": ["aether:ambrosium_ore", "aether:zanite_ore", "aether:gravitite_ore"],
    "alexscaves:galena": ["alexscaves:galena_iron_ore"],
    "alexscaves:guanostone": ["alexscaves:guanostone_redstone_ore"],
    "alexscaves:radrock": ["alexscaves:radrock_uranium_ore"],
}
IGNORED = ["alexscaves:coprolith_coal_ore"]


def main():
    items = set(open(ITEMS, encoding="utf-8").read().split())
    groups = {}  # host stone -> ores
    for i in sorted(items):
        ns, _, path = i.partition(":")
        if ns != "seamlessores" or not path.endswith("_ore"):
            continue
        prefix = max((p for p in SEAMLESS if path.startswith(p + "_")), key=len, default=None)
        if prefix is None:
            raise SystemExit(f"unknown Seamless Ores stone in {i}; add it to SEAMLESS")
        (IGNORED if path.endswith("_coal_ore") else groups.setdefault(SEAMLESS[prefix], [])).append(i)
    for stone, ores in OTHER.items():
        groups.setdefault(stone, []).extend(o for o in ores if o in items)
    missing = [b for b in list(groups) + [o for v in groups.values() for o in v] + IGNORED if b not in items]
    if missing:
        raise SystemExit("not in the registry: " + ", ".join(missing))

    lines = [
        "// Generated by pack/tools/gen_ore_magnet.py - do not edit by hand.",
        "// The Twilight Forest Ore Magnet pulls an ore from c:ores_in_ground/<x> and leaves the block of",
        "// c:ore_bearing_ground/<x> in its place; these groups cover the ores of Seamless Ores, the Aether and Alex's Caves.",
        "ServerEvents.tags('block', event => {",
    ]
    for stone in sorted(groups):
        name = "wilds_" + re.sub(r"[^a-z0-9]+", "_", stone.split(":")[1])
        if stone.split(":")[0] != "minecraft":
            name = "wilds_" + stone.replace(":", "_")
        lines.append(f"  event.add('c:ore_bearing_ground/{name}', '{stone}')")
        lines.append(f"  event.add('c:ores_in_ground/{name}', {json.dumps(sorted(groups[stone]))})")
    lines.append(f"  event.add('twilightforest:ore_magnet/ore_safe_replace_block', {json.dumps(sorted(groups))})")
    lines.append(f"  event.add('twilightforest:ore_magnet/ignored_ores', {json.dumps(sorted(IGNORED))})")
    lines.append("})")
    open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print(f"{sum(len(v) for v in groups.values())} ores in {len(groups)} stones, {len(IGNORED)} ignored -> {OUT}")


main()
